CREATE TABLE cashier_shifts (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                staff_id BIGINT NOT NULL,

                                venue_id BIGINT NOT NULL,

                                opened_at TIMESTAMP WITH TIME ZONE
                                                NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                opening_cash NUMERIC(12,2) NOT NULL,

                                closed_at TIMESTAMP WITH TIME ZONE,

                                expected_closing_cash NUMERIC(12,2),

                                actual_closing_cash NUMERIC(12,2),

                                cash_difference NUMERIC(12,2),

    -- OPEN / CLOSED
                                status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

                                notes TEXT,

                                created_at TIMESTAMP WITH TIME ZONE
                                    NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_cashier_shift_staff
                                    FOREIGN KEY (staff_id)
                                        REFERENCES users(id),

                                CONSTRAINT fk_cashier_shift_venue
                                    FOREIGN KEY (venue_id)
                                        REFERENCES venues(id),

                                CONSTRAINT chk_shift_opening_cash
                                    CHECK (opening_cash >= 0),

                                CONSTRAINT chk_shift_expected_cash
                                    CHECK (
                                        expected_closing_cash IS NULL
                                            OR expected_closing_cash >= 0
                                        ),

                                CONSTRAINT chk_shift_actual_cash
                                    CHECK (
                                        actual_closing_cash IS NULL
                                            OR actual_closing_cash >= 0
                                        ),

                                CONSTRAINT chk_shift_closed_time
                                    CHECK (
                                        closed_at IS NULL
                                            OR closed_at >= opened_at
                                        )
);

CREATE TABLE cash_movements (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                cashier_shift_id BIGINT NOT NULL,

    -- CASH_IN / CASH_OUT
                                movement_type VARCHAR(20) NOT NULL,

    -- BOOKING_PAYMENT
    -- ORDER_PAYMENT
    -- REFUND
    -- CASH_ADJUSTMENT
    -- OTHER
                                source_type VARCHAR(50) NOT NULL,

                                amount NUMERIC(12,2) NOT NULL,

    -- ID của booking/payment/order liên quan nếu có
                                reference_id BIGINT,

                                description TEXT,

                                created_by BIGINT NOT NULL,

                                created_at TIMESTAMP WITH TIME ZONE
                                    NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_cash_movement_shift
                                    FOREIGN KEY (cashier_shift_id)
                                        REFERENCES cashier_shifts(id)
                                        ON DELETE CASCADE,

                                CONSTRAINT fk_cash_movement_created_by
                                    FOREIGN KEY (created_by)
                                        REFERENCES users(id),

                                CONSTRAINT chk_cash_movement_amount
                                    CHECK (amount > 0),

                                CONSTRAINT chk_cash_movement_type
                                    CHECK (
                                        movement_type IN ('CASH_IN', 'CASH_OUT')
                                        )
);

