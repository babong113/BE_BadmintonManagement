CREATE OR REPLACE FUNCTION enforce_booking_detail_venue()
RETURNS TRIGGER AS $$
DECLARE
    booking_venue_id BIGINT;
    court_venue_id BIGINT;
BEGIN
    SELECT venue_id INTO booking_venue_id
    FROM bookings
    WHERE id = NEW.booking_id;

    SELECT venue_id INTO court_venue_id
    FROM courts
    WHERE id = NEW.court_id;

    IF booking_venue_id IS DISTINCT FROM court_venue_id THEN
        RAISE EXCEPTION 'Court % khong thuoc venue cua booking %', NEW.court_id, NEW.booking_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_detail_same_venue
    BEFORE INSERT OR UPDATE OF booking_id, court_id
    ON booking_details
    FOR EACH ROW
    EXECUTE FUNCTION enforce_booking_detail_venue();

CREATE OR REPLACE FUNCTION enforce_booking_venue_update()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.venue_id IS DISTINCT FROM OLD.venue_id
        AND EXISTS (
            SELECT 1
            FROM booking_details bd
            JOIN courts c ON c.id = bd.court_id
            WHERE bd.booking_id = NEW.id
              AND c.venue_id <> NEW.venue_id
        ) THEN
        RAISE EXCEPTION 'Tat ca san trong booking % phai thuoc venue %', NEW.id, NEW.venue_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_same_venue_on_update
    BEFORE UPDATE OF venue_id
    ON bookings
    FOR EACH ROW
    EXECUTE FUNCTION enforce_booking_venue_update();
